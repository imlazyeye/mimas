/// The width of a glyph's cell: three pixels of glyph and one of spacing.
pub(crate) const CELL_W: i64 = 4;

/// The height of a glyph's cell: five pixels of glyph and one of spacing, which the descenders of
/// g, j, p, q, y and the comma and semicolon draw into.
pub(crate) const CELL_H: i64 = 6;

/// The glyph for `c`, as six rows with the leftmost pixel in bit 2. Anything the font doesn't have
/// is a box.
pub(crate) fn glyph(c: char) -> [u8; 6] {
    match c {
        ' '..='~' => GLYPHS[c as usize - ' ' as usize],
        _ => GLYPHS[95],
    }
}

