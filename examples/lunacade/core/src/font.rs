const GLYPHS: [[u8; 6]; 96] = {
    let mut out = [[0; 6]; 96];
    let mut i = 0;
    while i < 96 {
        let (block, col) = (i / 16, i % 16 * 4);
        let mut row = 0;
        while row < 6 {
            let bytes = SHEET[block][row].as_bytes();
            let mut x = 0;
            while x < 3 {
                if bytes[col + x] == b'#' {
                    out[i][row] |= 4 >> x;
                }
                x += 1;
            }
            row += 1;
        }
        i += 1;
    }
    out
};
